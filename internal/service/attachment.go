// Attachment errors surfaced through the error envelope.
var (
	ErrAttachmentTooLarge = errors.New("attachment exceeds the size limit")
	ErrAttachmentType     = errors.New("attachment extension is not allowed")
)

// Storage abstracts binary storage so an S3 implementation can join in P2
// (issue #15).
type Storage interface {
	Save(ctx context.Context, path string, r io.Reader) (int64, error)
	Open(ctx context.Context, path string) (io.ReadCloser, error)
}

// AttachmentService implements upload and download (issue #15).
type AttachmentService struct {
	DB             *sql.DB
	Bus            *events.Bus
	Storage        Storage
	MaxBytes       int64
	AllowedExts    map[string]struct{}
}

// NewAttachmentService wires the service with config-derived limits.
func NewAttachmentService(db *sql.DB, bus *events.Bus, storage Storage, maxBytes int64, exts []string) *AttachmentService {
	set := make(map[string]struct{}, len(exts))
	for _, e := range exts {
		set[strings.ToLower(e)] = struct{}{}
	}
	return &AttachmentService{DB: db, Bus: bus, Storage: storage, MaxBytes: maxBytes, AllowedExts: set}
}

// Upload stores a file for a ticket. The stored path is generated by the
// server: tenant/month/uuid+ext — the user-supplied filename never reaches
// the filesystem, which kills path traversal by construction.
func (s *AttachmentService) Upload(ctx context.Context, ticketID int64, filename string, contentType string, r io.Reader, timelineID *int64) (*AttachmentBrief, error) {
	ac, err := appctx.MustFrom(ctx)
	if err != nil {
		return nil, err
	}
	ticket, err := (&repository.Tickets{Q: s.DB}).ByID(ctx, ticketID)
	if err != nil {
		return nil, err
	}
	if ac.Role == model.RoleRequester && ticket.CreatorID != ac.UserID {
		return nil, ErrTicketNotFound
	}

	ext := strings.ToLower(filepath.Ext(filename))
	if ext == "." {
		ext = ""
	}
	if _, ok := s.AllowedExts[ext]; !ok {
		return nil, ErrAttachmentType
	}

	// Read at most MaxBytes+1: an over-limit file is detected without
	// buffering it whole.
	limited := io.LimitReader(r, s.MaxBytes+1)
	buf := &bytesBuffer{}
	hasher := newSHA256()
	size, err := copyTo(buf, io.TeeReader(limited, hasher))
	if err != nil {
		return nil, err
	}
	if size > s.MaxBytes {
		return nil, ErrAttachmentTooLarge
	}

	relPath := fmt.Sprintf("%d/%s/%s%s", ac.TenantID, time.Now().UTC().Format("2006-01"), uuid.NewString(), ext)
	if _, err := s.Storage.Save(ctx, relPath, buf.Reader()); err != nil {
		return nil, err
	}

	a := &model.Attachment{
		TenantID:   ac.TenantID,
		TicketID:   ticketID,
		TimelineID: timelineID,
		Filename:   filepath.Base(filename),
		SizeBytes:  size,
		ContentType: detectContentType(contentType, ext),
		StoragePath: relPath,
		SHA256:      hasher.hex(),
		UploaderID:  ac.UserID,
	}

	var id int64
	err = repository.WithTx(ctx, s.DB, func(tx *sql.Tx) error {
		var err error
		id, err = (&repository.Attachments{Q: tx}).Insert(ctx, a)
		if err != nil {
			return err
		}
		if timelineID == nil {
			meta, _ := json.Marshal(map[string]any{
				"attachment_id": id, "filename": a.Filename,
			})
			tlID, err := (&repository.Timeline{Q: tx}).Insert(ctx, ticketID, model.KindSystem, ac.UserID,
				"上传了附件 "+a.Filename, meta)
			if err != nil {
				return err
			}
			if _, err := tx.ExecContext(ctx,
				`UPDATE attachments SET timeline_id = $1 WHERE id = $2 AND tenant_id = $3`,
				tlID, id, ac.TenantID); err != nil {
				return err
			}
		}
		return nil
	})
	if err != nil {
		return nil, err
	}

	s.Bus.Publish(ctx, events.New(events.TopicTicketAttachmentAdded, ac.TenantID, map[string]any{
		"ticket_id":     ticket.ID,
		"number":        ticket.Number,
		"title":         ticket.Title,
		"attachment_id": id,
		"filename":      a.Filename,
		"uploader_id":   ac.UserID,
	}))
	return &AttachmentBrief{
		ID: id, Filename: a.Filename, SizeBytes: a.SizeBytes,
		ContentType: a.ContentType, CreatedAt: nowUTC(),
	}, nil
}

// Download authorizes and streams an attachment: tenant scope plus the
// requester-own-ticket rule; cross-tenant misses look like 404.
func (s *AttachmentService) Download(ctx context.Context, attachmentID int64) (*model.Attachment, io.ReadCloser, error) {
	ac, err := appctx.MustFrom(ctx)
	if err != nil {
		return nil, nil, err
	}
	a, err := (&repository.Attachments{Q: s.DB}).ByID(ctx, attachmentID)
	if err != nil {
		return nil, nil, err
	}
	if ac.Role == model.RoleRequester {
		ticket, err := (&repository.Tickets{Q: s.DB}).ByID(ctx, a.TicketID)
		if err != nil {
			return nil, nil, err
		}
		if ticket.CreatorID != ac.UserID {
			return nil, nil, ErrTicketNotFound
		}
	}
	rc, err := s.Storage.Open(ctx, a.StoragePath)
	if err != nil {
		return nil, nil, err
	}
	return a, rc, nil
}

// ListByTicket is used by the detail endpoint and tests.
func (s *AttachmentService) ListByTicket(ctx context.Context, ticketID int64) ([]*model.Attachment, error) {
	return (&repository.Attachments{Q: s.DB}).ListByTicket(ctx, ticketID)
}

func detectContentType(declared, ext string) string {
	if declared != "" && declared != "application/octet-stream" {
		return declared
	}
	switch ext {
	case ".png":
		return "image/png"
	case ".jpg", ".jpeg":
		return "image/jpeg"
	case ".webp":
		return "image/webp"
	case ".gif":
		return "image/gif"
	case ".pdf":
		return "application/pdf"
	case ".zip":
		return "application/zip"
	case ".txt":
		return "text/plain"
	default:
		return "application/octet-stream"
	}
}

func nowUTC() string {
	return time.Now().UTC().Format(timeFormat)
}
